# Normalise keys once so "T-Shirt", "t shirts" and "tshirt" style inputs line up
# with the same normalisation the queries receive.
SYNONYMS: dict[str, str] = {normalize(k): v for k, v in _RAW.items()}


def expand_query(query: str) -> str:
    """Append tariff-style wording for any known seller phrase in the query."""
    padded = f" {normalize(query)} "
    extras = [val for key, val in SYNONYMS.items() if key and f" {key} " in padded]
    return query if not extras else f"{query} {' '.join(extras)}"
